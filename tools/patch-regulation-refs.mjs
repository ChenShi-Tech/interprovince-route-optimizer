#!/usr/bin/env node
/**
 * 依据归档原件修正费率数据中的法规引用。
 *
 * 起因：归档发改价格规〔2025〕1490号 附件4《跨省跨区专项工程输电价格定价办法》后核对原文，
 * 发现两处引用已过期：
 *   ① 9 条记录的计费口径引「1455号第十九条」，而 1455号 已自 2026-01-01 起废止，
 *      同一规定现为 1490号第十八条。
 *   ② 「单一容量电价」的规则依据引的是 2017年2269号，该文号早已被 2021年1455号、
 *      再被 2025年1490号 取代。现行表述见 1490号第七条（一般实行单一电量电价制）
 *      及其例外条款（清洁能源或以联网功能为主的工程可探索两部制或单一容量制）。
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const p = path.join(root, 'data/fixed-prices.json');
const fp = JSON.parse(fs.readFileSync(p, 'utf8'));

// ① 计费口径：1455号第十九条 → 1490号第十八条
let n1 = 0;
for (const r of fp.专项工程) {
  if ((r.计费口径 || '').includes('1455')) {
    r.计费口径 = r.计费口径.replace(
      /依据发改价格规〔2021〕1455号第十九条/,
      '依据发改价格规〔2025〕1490号第十八条（2026-01-01 起施行；原〔2021〕1455号第十九条已随该文废止）'
    );
    n1++;
  }
}

// ② 容量制折算口径：补上官方依据
fp._容量制折算说明 = [
  '单一容量电价制工程不按电量收费，其边际输电成本为 0，无法直接与「元/兆瓦时」口径比对。',
  '本工具按「容量电价 × 1000 ÷ 容量制折算利用小时」折算为等效度电成本，仅用于路径比选，标注为折算值。',
  '折算利用小时取 4500 小时，依据发改价格规〔2025〕1490号 附件4 第九条：',
  '「设计利用小时按政府主管部门批复的项目核准文件确定，文件中未明确的原则上按 4500 小时计算」。',
  '注意：云霄直流自 2026-06 起已引入输电权市场化交易，实际边际成本不再为 0（报价区间 25.6~100 元/兆瓦时）。',
].join('\n');

// ③ 法规谱系说明
fp._法规说明 = [
  '跨省跨区专项工程输电价格的定价规则谱系：',
  '  发改价格规〔2017〕2269号 → 发改价格规〔2021〕1455号 → 发改价格规〔2025〕1490号（现行）。',
  '现行 1490号 附件4 第七条：跨省跨区专项工程输电价格实行单一电量电价制。',
  '  例外（同附件后半段）：对以输送清洁能源电量为主，或以联网功能为主的专项工程，',
  '  可探索通过两部制或单一容量制形成输电价格。',
  '因此现存的两条单一容量电价制工程与之相符：',
  '  辛洹线（华北—华中间联络线，联网功能为主）、云霄直流（闽粤联网工程）。',
  '两者的核价文件仍为存量依据：辛洹线见发改价格〔2018〕1227号，云霄直流见发改价格〔2022〕1604号。',
  '⚠️ 1490号 第二十四条明确：〔2021〕1455号 自 2026-01-01 起废止。',
  '原件存于 docs/原始文件/S13-附件4-跨省跨区专项工程输电价格定价办法.pdf。',
].join('\n');

fs.writeFileSync(p, JSON.stringify(fp, null, 2) + '\n');
console.log(`✅ 法规引用已修正`);
console.log(`   计费口径更新：${n1} 条`);
console.log(`   新增 _容量制折算说明（含 4500 小时的官方依据）`);
console.log(`   新增 _法规说明（定价办法谱系与现行条款）`);
